"""Generate docs/STATUS.md: measured project status, not typed (shared file).

Usage:  python scripts/status_report.py [--no-tests]

Writes, from what is on disk right now:
  * results files: exists, schema-valid, generated_at, source
  * spec components: the file that implements each one exists
  * proof checks from results/checks.json (written by the last pytest run)
  * pytest pass/fail/skip counts (runs `pytest -q` unless --no-tests)
"""
