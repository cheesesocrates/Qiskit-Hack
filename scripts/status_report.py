def run_pytest() -> str:
    env = dict(os.environ, PYTHONPATH=str(ROOT), MPLBACKEND="Agg", PYTHONIOENCODING="utf-8")
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:warnings"], cwd=ROOT, env=env,
                          capture_output=True, text=True, encoding="utf-8", errors="replace")
    tail = [line for line in proc.stdout.splitlines() if re.search(r"\d+ (passed|failed|skipped|error)", line)]
    return tail[-1].strip("= ") if tail else f"pytest exit code {proc.returncode}, no summary line"


def main() -> int:
    no_tests = "--no-tests" in sys.argv
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = ["# FairShed status (generated)", "",
             f"Generated by `python scripts/status_report.py` at {now}. Do not edit by hand.", ""]

    lines += ["## Tests", ""]
    lines.append(f"- pytest: {'not run (--no-tests)' if no_tests else run_pytest()}")
    chk_path = RESULTS / "checks.json"
    if chk_path.exists():
        chk = json.loads(chk_path.read_text(encoding="utf-8"))
        s = chk.get("summary", {})
        lines.append(f"- proof checks in results/checks.json: {s.get('passed')} of {s.get('total')} pass "
                     f"(written {chk.get('generated_at')})")
    lines.append("")

    lines += ["## Results files", "", "| File | Exists | Schema-valid | generated_at | source |", "|---|---|---|---|---|"]
    for pattern, schema_name in load_index().items():
        paths = sorted(RESULTS.glob(pattern))
        if not paths:
            lines.append(f"| results/{pattern} | no | n/a | n/a | n/a |")
            continue
        for p in paths:
            errs = validate_file(p, schema_name)
            try:
                doc = json.loads(p.read_text(encoding="utf-8"))
            except Exception:
                doc = {}
            lines.append(f"| results/{p.relative_to(RESULTS).as_posix()} | yes | {'yes' if not errs else 'NO: ' + errs[0][:80]} "
                         f"| {doc.get('generated_at', 'n/a')} | {doc.get('source', 'n/a')} |")
    lines.append("")

    lines += ["## Spec components", "", "| Component | Implemented in | File exists | Result file |", "|---|---|---|---|"]
    for name, path, res in COMPONENTS:
        exists = (ROOT / path).exists()
        rcol = "n/a" if res is None else (f"results/{res} " + ("present" if (RESULTS / res).exists() else "MISSING"))
        lines.append(f"| {name} | `{path}` | {'yes' if exists else 'NO'} | {rcol} |")
    lines.append("")

    if chk_path.exists():
        lines += ["## Proof checks", "", "| ID | Check | Passed | Detail |", "|---|---|---|---|"]
        for c in sorted(chk["checks"], key=lambda c: c["id"]):
            detail = str(c.get("detail") or "").replace("|", "/")[:120]
            lines.append(f"| {c['id']} | {c['name']} | {'yes' if c['passed'] else 'NO'} | {detail} |")
        lines.append("")

    out = ROOT / "docs" / "STATUS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
