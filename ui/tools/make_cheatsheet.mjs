// Writes docs/TEAM_CHEATSHEET.md from results/*.json (Area 3). Run: node ui/tools/make_cheatsheet.mjs
// The numbers are read from the results files, never typed by hand. A missing file gives "not available".
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const load = (rel) => { const p = join(ROOT, 'results', rel); try { return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null; } catch (e) { return null; } };
const f = (v, d = 2) => (v === null || v === undefined ? 'n/a' : Number(v).toFixed(d));
const pct = (x) => { if (x === null || x === undefined) return 'n/a'; const v = x * 100; return v < 10 ? `${v.toFixed(2)}%` : `${v.toFixed(0)}%`; };
const NA = 'not available (results file missing)';

const abl = load('ablation.json'), lot = load('lottery.json'), cnt = load('counting.json'), rsk = load('risk.json');
const rep = load('replay.json'), sca = load('scaling.json'), fc = load('forecast.json'), chk = load('checks.json');

const nums = [];
if (abl) {
  const ref = abl.reference;
  const rows = abl.rows.filter((r) => r.instance === abl.instance_name);
  const q = rows.filter((r) => r.kind === 'quantum' && r.method !== 'dicke_uniform');
  const guess = ref.n_optimal / ref.n_valid;
  const bp = q.reduce((a, b) => (b.p_optimal > a.p_optimal ? b : a));
  const br = q.reduce((a, b) => (b.approx_ratio > a.approx_ratio ? b : a));
  const rr = rows.find((r) => r.method === 'round_robin');
  const pen = q.filter((r) => r.method.startsWith('penalty'));
  nums.push([`${ref.n_valid} valid plans in the base case, ${ref.n_optimal} tie for best (${br.n_qubits} qubits).`, 'Results > Scoreboard, summary box']);
  nums.push([`Best circuit (${bp.label}): one try finds a best plan ${pct(bp.p_optimal)} of the time, ${(bp.p_optimal / guess).toFixed(1)} times a random guess (${pct(guess)}).`, 'Results > Scoreboard, "Chance one try finds the best plan"']);
  nums.push([`Average quantum try reaches ${(br.approx_ratio * 100).toFixed(0)}% of the way to the best plan${rr ? `; round-robin reaches ${(rr.approx_ratio * 100).toFixed(0)}%` : ''}. Exact search: 100%.`, 'Results > Scoreboard, "How close to best"']);
  if (pen.length) nums.push([`Penalty QAOA gives valid plans in only ${pen.map((r) => `${r.feasibility_pct.toFixed(1)}%`).join(' and ')} of tries.`, 'Results > Scoreboard, "Valid tries"']);
} else nums.push([`Scoreboard numbers: ${NA}`, 'Results > Scoreboard']);
if (lot && lot.tie_groups.length) {
  const g = lot.tie_groups[0];
  nums.push([`${g.n_plans} tied best plans each get ${pct(g.prob_min)} per try; the largest difference is ${g.prob_spread.toExponential(1)}.`, 'Results > Fair lottery']);
} else nums.push([`Fair lottery: ${NA}`, 'Results > Fair lottery']);
nums.push([cnt ? `Counting on a ${cnt.instance.n_feeders} x ${cnt.instance.n_hours} block: estimate ${f(cnt.estimated_count)}, exact ${cnt.exact_count}, interval ${f(cnt.ci[0])} to ${f(cnt.ci[1])}.` : `Counting: ${NA}`, 'Results > Uncertainty and counting']);
nums.push([rsk ? `CVaR ${(rsk.alpha * 100).toFixed(0)}: exact ${f(rsk.exact.cvar, 3)} MW, estimate ${f(rsk.estimated.cvar, 3)} MW; chance of an unplanned cut ${f(rsk.exact.tail_prob, 3)}.` : `Risk: ${NA}`, 'Results > Uncertainty and counting']);
if (rep) {
  const s = rep.summary; const nq = rep.frames.filter((x) => /quantum/i.test(x.solver_used)).length;
  nums.push([`Replay: ${nq} of ${s.n_frames} hours planned by the quantum circuit; ${s.matches_exact_count} matched the best plan; ${rep.frames.filter((x) => x.audit_passed).length} passed every rule.`, 'Replay and rules > Watch it hour by hour']);
} else nums.push([`Replay: ${NA}`, 'Replay and rules']);
if (sca) {
  const ok = sca.points.filter((p) => p.status === 'ok');
  const big = Math.max(...ok.map((p) => p.n_qubits));
  const hi = ok.filter((p) => p.n_qubits === big && p.bond_dim !== null).sort((a, b) => b.bond_dim - a.bond_dim)[0];
  nums.push([`Bigger problems: ${ok.length} of ${sca.points.length} points ran, up to ${big} qubits; ${hi ? `${(hi.approx_ratio * 100).toFixed(0)}% at bond dimension ${hi.bond_dim}` : 'n/a'}.`, 'Results > Bigger problems']);
} else nums.push([`Bigger problems: ${NA}`, 'Results > Bigger problems']);
nums.push([fc ? `Forecast misses by ${f(fc.metrics.mae_mw)} MW per hour on average in the test week (R squared ${f(fc.metrics.r2)}).` : `Forecast: ${NA}`, 'Results > Shortage forecast']);
if (chk) nums.push([`${chk.summary.passed} of ${chk.summary.total} automated proof checks pass.`, 'Results > Scoreboard, bottom']);

const md = `# FairShed team cheatsheet

Generated by \`node ui/tools/make_cheatsheet.mjs\` from \`results/*.json\` on ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC.
Re-run it after \`python scripts/tasks.py demo\`. Do not edit the numbers by hand.

## The project in 5 sentences

1. When there is not enough electricity, a utility must switch some neighbourhood power lines (feeders) off for an hour at a time.
2. FairShed decides which feeders go off in each hour: it never cuts hospitals, water pumps or telecom towers, spreads the outage hours fairly and avoids cutting the same area twice in a row.
3. Each feeder-hour that can be cut is one yes or no switch, and one qubit; a quantum circuit (QAOA) samples schedules that always meet the hourly quota, and the best valid one of 256 tries is used.
4. Every quantum number is checked against the exact answer from a normal computer, and the dashboard says plainly where quantum loses.
5. Everything runs on a simulator with synthetic feeders and demand (the weather snapshot is real); no speed-up is claimed.

## The methods in one line each

- **Exact search (brute force, MILP):** checks every valid plan; the reference everything is scored against.
- **Round-robin and random:** simple rules with no optimisation; round-robin breaks the back-to-back limit in a heatwave.
- **Dicke + XY-mixer QAOA:** starts inside the valid plans and never leaves them; every try is valid.
- **Penalty QAOA:** ordinary mixer plus a fine for broken rules; wastes most tries; a weak baseline.
- **Grover-mixer QAOA:** equally good plans get exactly equal chances, so ties are a fair lottery.
- **Quantum counting:** amplitude estimation counts the valid plans, on a small 4 x 2 block.
- **Risk by amplitude estimation:** expected miss, VaR and CVaR of the peak-hour plan, from forecast errors.
- **Grover Adaptive Search:** keeps asking for a better plan; small block only.
- **MPS scaling:** runs the circuit on bigger problems with a limited-memory simulator; behaviour, not advantage.
- **Ridge forecast and receding horizon:** a classical forecast sets the quotas; the plan is re-made every hour.

## The numbers to know (from the results files)

| # | Number | Where on the dashboard |
|---|---|---|
${nums.slice(0, 10).map((n, i) => `| ${i + 1} | ${n[0]} | ${n[1]} |`).join('\n')}

## Honest limits (say these before anyone asks)

- Simulator only. Nothing ran on quantum hardware.
- Synthetic data: feeders, demand and the outage ledger are made up; only the weather snapshot is real.
- At this size a normal computer finds the exact best plan, and it is better than the quantum circuit.
- A single try rarely lands on the best plan, so the plan used is the best of 256 tries; it still misses the best plan in some replay hours.
- No speed-up is claimed. The bigger-problems curve is a classical simulation.
`;
writeFileSync(join(ROOT, 'docs', 'TEAM_CHEATSHEET.md'), md, 'utf8');
console.log('wrote docs/TEAM_CHEATSHEET.md');
